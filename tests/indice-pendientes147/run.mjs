import assert from 'node:assert/strict';
import {newPendingSnapshot147,pendingApply147,pendingView147,PENDING_KINDS147} from '../../worker/modules/indice-pendientes147.mjs';
const now='2026-10-30T19:00:00Z';
let s=newPendingSnapshot147();
assert.equal(pendingView147(s,{rol:'SUPERADMIN'}).items.length,0);
s=pendingApply147(s,[{accion:'UPSERT',tipo:'EVENTO_VIP',id:'evt1',ciudad_id:'DOL',resumen:'Evento a revisar'},{accion:'UPSERT',tipo:'REVISION_ADULTO',id:'evt1',ciudad_id:'DOL'}],now);
assert.equal(s.items.length,2);
assert.equal(pendingView147(s,{rol:'SUPERADMIN'}).cantidades.EVENTO_VIP,1);
assert.equal(pendingView147(s,{rol:'ADMIN_LOCAL',ciudades:['DOL']}).cantidades.REVISION_ADULTO,0);
assert.equal(pendingView147(s,{rol:'ADMIN_LOCAL',ciudades:['OTRA']}).items.length,0);
const prev=s.revision;
s=pendingApply147(s,[{accion:'REMOVE',tipo:'EVENTO_VIP',id:'evt1'}],now);
assert.equal(s.revision,prev+1);
assert.equal(s.items.length,1);
assert.equal(pendingView147({...s,estado:'INCOMPLETO'},{rol:'SUPERADMIN'}).cantidades,null);
assert.throws(()=>pendingApply147({...s,estado:'INCOMPLETO'},[],now));
assert.throws(()=>pendingView147(s,{rol:'PUBLICO'}));
assert.equal(PENDING_KINDS147.length,12);
console.log('indice-pendientes147: 10 comprobaciones OK (lógica local; sin servidor)');
