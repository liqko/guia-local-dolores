import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../plataforma/login.html',import.meta.url),'utf8');
const start=html.indexOf('function promoEstadoVisible(');
const end=html.indexOf('function renderPromosTable(',start);
const list={innerHTML:''};
const context={Intl,Date,publicacionPausada:p=>!!p.pausado,document:{getElementById:()=>list},htmlEscape:s=>String(s).replaceAll('<','&lt;'),toDateInputValue:s=>s,GLD_MEDIA:{imageUrl:()=>''},promoState:{sedes:[]}};
vm.createContext(context);
vm.runInContext(html.slice(start,end),context);
context.renderPromosCards([{promo_id:'saved-promo',promo:'Promoción existente',pausado:false}]);
assert(list.innerHTML.includes('Promoción existente'));
for(const action of ['edit','pause','duplicate','delete'])assert(list.innerHTML.includes(`data-promo-action="${action}"`));
context.renderPromosCards([{promo_id:'saved-promo',promo:'Promoción existente',pausado:true}]);
assert(list.innerHTML.includes('Reanudar'));
for(const block of html.matchAll(/([^{}]+)\{([^{}]*)\}/g))if(/display\s*:\s*none\s*!important/.test(block[2]))assert(!block[1].includes('#promos-list .card-list'),'Stored promos must remain visible on desktop');
for(const [id,max] of [['promo-text',300],['promo-otros',120]])assert(new RegExp(`<textarea[^>]*id="${id}"[^>]*maxlength="${max}"[^>]*rows="4"`).test(html));
for(const script of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi))new vm.Script(script[1]);
console.log('PASS: stored promos, all actions, desktop visibility, multiline limits and script syntax');
